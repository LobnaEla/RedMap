from typing import List


def create_judge_prompt(
    original_text: str,
    iocs: str,
    llm_predicted_techniques: List[str],  # Primary list to validate
    ras_evidence_techniques: List[str],  # RAS
) -> str:
    """
    Creates a forensic-style judge prompt that validates the LLM's predictions
    using RAS (Retrieval-Augmented Search) results as evidence anchors.

    The judge evaluates: Was the LLM correct? Why or why not?
    RAS is treated as a reference corpus, not a peer system.
    """

    prompt = f"""You are a senior MITRE ATT&CK forensic analyst and validation judge.
Your task is to **audit the predictions made by a Large Language Model (LLM)** on a piece of Cyber Threat Intelligence (CTI).
You will use **Retrieval-Augmented Search (RAS) results as objective evidence** to determine whether each LLM-predicted technique is valid.

## 🔍 Mission: Forensic Validation of LLM Predictions
For each technique predicted by the LLM, you must answer:
1. ✅ **WHY was this technique VALIDATED?** → Is there direct or strong inferential evidence in the text **AND** support from RAS?
2. ❌ **WHY was this technique REJECTED?** → Is the prediction unsupported by text, inconsistent with context, or absent in RAS?

> ⚠️ **Critical Rule**: The RAS results are your **evidence base**, not a competing system.  
> If a technique is in the LLM's output but **not supported by RAS or the original text**, it should be **rejected unless strongly justified by context**.

---

## 📄 Original CTI Content
{original_text}


## 🛑 Indicators of Compromise (IOCs)
{iocs}


---

## 🧩 Inputs for Validation

### LLM-Predicted Techniques (To Be Audited)
These are the techniques generated by the LLM via in-context learning:
{llm_predicted_techniques}

### RAS Evidence Techniques (Reference Truth Anchor)
These techniques were retrieved by semantic search from a MITRE knowledge base.  
They represent **documented behaviors closely matching the input text**:
{ras_evidence_techniques}

> RAS is used as **evidence**, not as a voting system.  
> Your job is to assess whether the LLM's predictions are **grounded in this kind of retrievable knowledge**.

---

## Validation Framework

For each technique in the **LLM-Predicted Techniques** list, perform the following:

### 1. Evidence Assessment
- Does the **original text** contain explicit or strongly implied evidence for this technique?
- Is this technique present in the **RAS evidence list**?
- If not in RAS, is there a **strong contextual justification** (e.g., logical inference, IOC alignment)?

### 2. Contextual Fit
- Does the technique fit the **attack phase** (initial access, execution, etc.) described?
- Are **prerequisites** for the technique satisfied in the scenario?
- Is the technique **operationally plausible** given other behaviors?

### 3. Confidence Scoring
- **High (0.8–1.0)**: Strong textual evidence + RAS support
- **Medium (0.5–0.79)**: Reasonable inference, but no RAS match or weak text support
- **Low (0.0–0.49)**: Speculative, hallucinated, or contradicted

> **Rule**: Techniques with **no RAS support AND weak textual evidence** must be rejected.

### 4. Rejection Analysis
If rejecting a technique, explain:
- What specific evidence is missing?
- Why might the LLM have hallucinated or overgeneralized?
- Is there a **better alternative** in the RAS list?

---

## 📥 Output Format (JSON)
{
    "validated_techniques": [
        // Only techniques that pass both textual and RAS-based validation
    ],
    "rejected_techniques": [
        // Techniques predicted by LLM but rejected
    ],
    "technique_analysis": {
        "T1234": {
            "status": "validated|rejected",
            "confidence": 0.92,
            "evidence": "Specific quote or behavior from text",
            "reasoning": "Why this technique is valid/invalid; reference RAS if relevant",
            "in_ras": true|false,
            "alternative": "T5678 (if rejected, suggest better fit)"
        }
    },
    "validation_summary": {
        "total_analyzed": {len(llm_predicted_techniques)},
        "validated_count": 0,
        "rejected_count": 0,
        "validation_rate": 0.0,
        "supported_by_ras_count": 0,
        "hallucinated_count": 0
    },
    "forensic_insights": {
        "llm_accuracy": "How well the LLM aligns with retrievable knowledge",
        "common_failure_modes": [
            "e.g., overgeneralization (T1059 instead of T1059.001)",
            "e.g., hallucination of tools not mentioned",
            "e.g., confusion between similar techniques"
        ],
        "ras_coverage": "What percentage of ground truth is in RAS?",
        "missing_in_both": [
            "Techniques not in LLM output nor RAS — potential blind spots"
        ],
        "operational_recommendations": [
            "e.g., 'Create detection rule for PowerShell -EncodedCommand'",
            "e.g., 'Hunt for PsExec usage in lateral movement logs'"
        ]
    }
}

---

## 🚨 Critical Directives

1. **Do NOT treat RAS as a peer system** — it is your **evidence base**.
2. **Presume LLM predictions are suspect until proven valid**.
3. **Reject if unsupported by text OR RAS**, unless inference is strong.
4. **Prefer specific sub-techniques** when evidence supports them.
5. **Cite exact text** for all validations.
6. **Identify hallucinations** — explain why the LLM might have invented a technique.
7. **Be conservative**: It's better to miss a technique than to validate a false one.

---

## ✅ Final Output Requirement
Your output must reflect a **forensic audit**, not a consensus vote.  
Only include techniques that are **grounded in evidence** from the text and supported (or plausibly extendable) from RAS.

Begin your forensic validation now."""

    return prompt
